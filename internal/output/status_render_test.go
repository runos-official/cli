// TestExistingRealPayloadShapesRenderUnchanged guards the risk the plan named
// for the containment gate: that a REAL payload carrying `link` or `replicas`
// with extra keys would have its rendering moved. Both shapes below are the
// live ones — `apps/network-access` rows ({type,name,link}, typed in
// internal/deploy as NetworkAccess) and the `replicas` block
// ({desired,ready,available}, per the service status handbook articles) — and
// both want strings were captured from the pre-change build.
func TestExistingRealPayloadShapesRenderUnchanged(t *testing.T) {
	networkAccess := []byte(`[{"type":"ingress","name":"web","link":"https://web.example.com"}]`)
	got := captureStdout(t, func() {
		_ = NewFormatter(false).Format(networkAccess, &manifest.Output{Type: "array", Fields: []manifest.OutputField{
			{Name: "type"}, {Name: "name"}, {Name: "link"},
		}})
	})
	want := "TYPE     NAME  LINK                     \n" +
		"----------------------------------------\n" +
		"ingress  web   https://web.example.com  \n"
	if got != want {
		t.Errorf("apps/network-access rendering moved:\ngot:\n%s\nwant:\n%s", got, want)
	}

	show := []byte(`{"id":"ab12c","replicas":{"desired":3,"ready":2,"available":2},` +
		`"networkAccess":[{"type":"ingress","name":"web","link":"https://web.example.com"}]}`)
	got = captureStdout(t, func() {
		_ = NewFormatter(false).Format(show, &manifest.Output{Type: "object", Fields: []manifest.OutputField{
			{Name: "id"}, {Name: "replicas"}, {Name: "networkAccess"},
		}})
	})
	want = "id           : ab12c\n" +
		"replicas     :\n" +
		"  available: 2\n" +
		"  desired  : 3\n" +
		"  ready    : 2\n" +
		"networkAccess: 1 entry\n" +
		"  LINK                     NAME  TYPE\n" +
		"  ----------------------------------------\n" +
		"  https://web.example.com  web   ingress\n"
	if got != want {
		t.Errorf("apps/show rendering moved:\ngot:\n%s\nwant:\n%s", got, want)
	}

	list := []byte(`[{"id":"ab12c","state":{"state":"healthy"},"replicas":{"desired":3,"ready":2,"available":2}}]`)
	got = captureStdout(t, func() {
		_ = NewFormatter(false).Format(list, &manifest.Output{Type: "array", Fields: []manifest.OutputField{
			{Name: "id"}, {Name: "state"}, {Name: "replicas"},
		}})
	})
	want = "ID     STATE    REPLICAS                \n" +
		"----------------------------------------\n" +
		"ab12c  healthy  2/3 ready, 2 available  \n"
	if got != want {
		t.Errorf("list-shaped status rendering moved:\ngot:\n%s\nwant:\n%s", got, want)
	}
}

// TestListShapedStatusRendering is the list-shaped surface, where the
// enriched status column meets the table's pre-existing 40-rune per-cell
// cap. THE STATE WORD MUST SURVIVE THAT CAP. Review finding, rework cycle 1:
// the first cut of this fix let the default branch emit keys in pure
// alphabetical order, so `state` sorted behind `backendName`, `message` and
// `reason` and the cap cut the cell before it. The column named STATE then
// carried no state at all, which inverts the objective's operator criterion
// on exactly the surface this story set out to repair. The default branch
// now leads with the keys the summary patterns consume, so the verdict is
// never the thing that gets elided.
//
// No manifest status read is list-shaped today (see the census test), so
// this exercises the real top-level array path against synthetic rows.
func TestListShapedStatusRendering(t *testing.T) {
	cases := []struct {
		name string
		body string
		// wantVisible must appear in the rendered cell.
		wantVisible []string
		// elided names what the 40-rune cap cuts for this row. Recorded,
		// not tolerated silently: --json carries the full value, and the
		// object-shaped surface every manifest status read declares has no
		// such cap.
		elided []string
	}{
		{
			name:        "backend attribution beside the state",
			body:        `[{"id":"ab12c","state":{"state":"unhealthy","backendName":"images-object-store","backendType":"minio"}}]`,
			wantVisible: []string{"state=unhealthy", "backendName=images-"},
			elided:      []string{"backendType=minio"},
		},
		{
			name:        "message and reason beside the state",
			body:        `[{"id":"ab12c","state":{"state":"unhealthy","message":"a backing service cannot serve","reason":"no usable drives"}}]`,
			wantVisible: []string{"state=unhealthy", "message=a backing"},
			elided:      []string{"reason=no usable drives"},
		},
		{
			name:        "short attribution fits whole",
			body:        `[{"id":"ab12c","state":{"state":"unhealthy","reason":"no drives"}}]`,
			wantVisible: []string{"state=unhealthy", "reason=no drives"},
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			out := captureStdout(t, func() {
				_ = NewFormatter(false).Format([]byte(tc.body), &manifest.Output{Type: "array", Fields: []manifest.OutputField{
					{Name: "id"}, {Name: "state"},
				}})
			})
			t.Logf("rendered:\n%s", out)

			// The health verdict is never what the cap cuts.
			if !strings.Contains(out, "unhealthy") {
				t.Errorf("the STATE column lost the state word entirely:\n%s", out)
			}
			for _, want := range tc.wantVisible {
				if !strings.Contains(out, want) {
					t.Errorf("expected %q in the cell:\n%s", want, out)
				}
			}
			for _, gone := range tc.elided {
				if strings.Contains(out, gone) {
					t.Logf("NOTE: %q now fits; the recorded elision list is stale, tighten it", gone)
				}
			}
			if len(tc.elided) > 0 && !strings.Contains(out, "...") {
				t.Errorf("expected the 40-rune cap to elide the tail:\n%s", out)
			}
		})
	}
}

// TestJSONOutputByteIdenticalToBody is criterion 5: the text-mode work did not
// touch the machine-readable path. Each fixture is stored in Go's canonical
// MarshalIndent form (see PROVENANCE.md), so the assertion is literal byte
// identity against the recorded response body, plus a structural round-trip
// check that survives any future re-indentation of the fixtures.
func TestJSONOutputByteIdenticalToBody(t *testing.T) {
	fixtures := enrichedFixtures(t)

	// The criterion-4 cell payloads too, so every payload in criteria 2-4 is
	// covered.
	fixtures["cell/backend-attribution"] = []byte("{\n  \"backendName\": \"images-object-store\",\n" +
		"  \"backendType\": \"minio\",\n  \"message\": \"a recorded backing service cannot serve\",\n" +
		"  \"state\": \"unhealthy\"\n}\n")
	fixtures["cell/contained-status"] = []byte("{\n  \"message\": \"pod not ready\",\n  \"state\": \"unhealthy\"\n}\n")

	for name, body := range fixtures {
		t.Run(name, func(t *testing.T) {
			out := captureStdout(t, func() {
				if err := NewFormatter(true).Format(body, &manifest.Output{Type: "object"}); err != nil {
					t.Fatalf("format json: %v", err)
				}
			})
			if out != string(body) {
				t.Errorf("--json output is not byte-identical to the body:\ngot:\n%q\nwant:\n%q", out, string(body))
			}
			var gotV, wantV any
			if err := json.Unmarshal([]byte(out), &gotV); err != nil {
				t.Fatalf("json output does not parse: %v", err)
			}
			if err := json.Unmarshal(body, &wantV); err != nil {
				t.Fatalf("body does not parse: %v", err)
			}
			if fmt.Sprintf("%v", gotV) != fmt.Sprintf("%v", wantV) {
				t.Errorf("json round-trip differs:\ngot  %v\nwant %v", gotV, wantV)
			}
		})
	}
}
